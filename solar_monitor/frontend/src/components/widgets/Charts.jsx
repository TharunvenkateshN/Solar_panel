import { CartesianGrid, Legend, Line, LineChart, ReferenceLine, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts'

const MARK = { SCENARIO: '#1c5bb8', COMMAND: '#c07a00', VERIFY: '#0b8f5a', HOTSPOT: '#c62828' }

export function TrendChart({ data, lines, unit, rightUnit, markers = [], thresholds = [], height = 240 }) {
  const byTick = Object.fromEntries(data.map((d) => [d.tick, d.sim_time]))
  return (
    <ResponsiveContainer width="100%" height={height}>
      <LineChart data={data} margin={{ top: 6, right: rightUnit ? 4 : 12, left: 0, bottom: 0 }}>
        <CartesianGrid strokeDasharray="3 3" stroke="var(--grid)" />
        <XAxis dataKey="tick" type="number" domain={['dataMin', 'dataMax']} stroke="var(--muted)" tickFormatter={(t) => byTick[t] || t} allowDecimals={false} minTickGap={28} />
        <YAxis yAxisId="l" stroke="var(--muted)" unit={unit} domain={['auto', 'auto']} width={rightUnit ? 50 : 56} />
        {rightUnit && <YAxis yAxisId="r" orientation="right" stroke="var(--muted)" unit={rightUnit} domain={[0, 100]} width={50} />}
        <Tooltip contentStyle={{ background: '#fff', border: '1px solid var(--border)', color: 'var(--text)', borderRadius: 8 }}
          labelFormatter={(t) => `sim ${byTick[t] || ''} (cycle ${t})`} formatter={(v) => (typeof v === 'number' ? v.toFixed(2) : v)} />
        <Legend />
        {thresholds.map((t) => <ReferenceLine key={t.label} yAxisId="l" y={t.y} stroke="#c07a00" strokeDasharray="5 4" label={{ value: t.label, fill: '#8a5700', fontSize: 11, position: 'insideBottomRight' }} />)}
        {markers.map((m) => <ReferenceLine key={m.id} yAxisId="l" x={m.tick} stroke={MARK[m.type]} strokeDasharray="2 3" ifOverflow="hidden" />)}
        {lines.map((l) => <Line key={l.key} yAxisId={l.right ? 'r' : 'l'} dataKey={l.key} name={l.name} stroke={l.color} dot={false} strokeWidth={2.2} isAnimationActive={false} connectNulls />)}
      </LineChart>
    </ResponsiveContainer>
  )
}

export const markersFrom = (s) => {
  const first = s.history[0]?.tick ?? 0
  return s.events.filter((e) => MARK[e.type] && e.tick >= first && (e.type !== 'HOTSPOT' || e.level === 'alert'))
    .map((e) => ({ id: e.id, tick: e.tick, type: e.type }))
}

export function MarkerLegend() {
  return (
    <p className="hint">Dashed markers:
      <span style={{ color: MARK.SCENARIO }}> scenario change</span> ·
      <span style={{ color: MARK.COMMAND }}> command / action</span> ·
      <span style={{ color: MARK.VERIFY }}> verification</span> ·
      <span style={{ color: MARK.HOTSPOT }}> hotspot alert</span>. History is generated by the simulation, not observed.</p>
  )
}

export function PowerChart({ s, height }) {
  return <TrendChart data={s.history} unit=" W" markers={markersFrom(s)} height={height}
    lines={[{ key: 'power', name: 'Measured (INA219)', color: '#0b8f5a' }, { key: 'expected', name: 'Expected (digital twin)', color: '#1c5bb8' }]} />
}
export function DeviationChart({ s, height }) {
  const thr = s.config.soiling_dev_thresh_pct
  return <TrendChart data={s.history} unit=" %" rightUnit=" %" markers={markersFrom(s)} height={height}
    thresholds={thr ? [{ y: thr, label: `${thr}% threshold` }] : []}
    lines={[{ key: 'deviation', name: 'Deviation % (left)', color: '#c07a00' }, { key: 'health', name: 'Health % (right)', color: '#0a6cbd', right: true }]} />
}
export function TempChart({ s, height }) {
  return <TrendChart data={s.history} unit=" °C" markers={markersFrom(s)} height={height}
    lines={[{ key: 't_max', name: 'Thermal max', color: '#c62828' }, { key: 't_avg', name: 'Thermal average', color: '#c07a00' }]} />
}

export function IvCurve({ s, height = 230 }) {
  const c = s.result?.features?.curve
  if (!c) return null
  const data = c.V.map((v, i) => ({ v, i: c.I[i], p: +(v * c.I[i]).toFixed(3) }))
  const iv = s.result.features.iv_features
  return (
    <ResponsiveContainer width="100%" height={height}>
      <LineChart data={data} margin={{ top: 6, right: 4, left: 0, bottom: 0 }}>
        <CartesianGrid strokeDasharray="3 3" stroke="var(--grid)" />
        <XAxis dataKey="v" type="number" domain={[0, 'dataMax']} unit=" V" stroke="var(--muted)" tickFormatter={(x) => x.toFixed(0)} />
        <YAxis yAxisId="l" stroke="var(--muted)" unit=" A" width={54} />
        <YAxis yAxisId="r" orientation="right" stroke="var(--muted)" unit=" W" width={50} />
        <Tooltip contentStyle={{ background: '#fff', border: '1px solid var(--border)', borderRadius: 8 }} formatter={(v) => v.toFixed(2)} labelFormatter={(v) => `${(+v).toFixed(1)} V`} />
        <Legend />
        <ReferenceLine yAxisId="l" x={iv.Vmpp} stroke="#c07a00" strokeDasharray="4 3" label={{ value: 'MPP', fill: '#8a5700', fontSize: 11 }} />
        <Line yAxisId="l" dataKey="i" name="Current (A)" stroke="#0a6cbd" dot={false} strokeWidth={2.2} isAnimationActive={false} />
        <Line yAxisId="r" dataKey="p" name="Power (W)" stroke="#0b8f5a" dot={false} strokeWidth={2.2} isAnimationActive={false} />
      </LineChart>
    </ResponsiveContainer>
  )
}
